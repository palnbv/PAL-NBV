"""Optional multimodal candidate selection. No images or prompts are saved locally."""

import base64
import json
import logging

import cv2
import numpy as np
from openai import OpenAI, OpenAIError
from scipy.ndimage import distance_transform_edt

from .prompt import get_prompt

LOG = logging.getLogger(__name__)


def _image_part(bgr):
    ok, png = cv2.imencode(".png", bgr)
    if not ok:
        raise ValueError("Could not encode the LLM input image")
    encoded = base64.b64encode(png).decode("ascii")
    return {"type": "image_url", "image_url": {"url": f"data:image/png;base64,{encoded}"}}


class LLMSelector:
    def __init__(self, model):
        self.model = model
        self.client = OpenAI(timeout=30.0, max_retries=0)

    def __call__(self, obs, occupancy, position, yaw):
        grid = occupancy.get_occupancy_grid().cpu().numpy()
        inflated = distance_transform_edt(grid < 2) * occupancy.grid_resolution <= 1.0
        clusters = occupancy._detect_obstacle_clusters(grid)
        candidates = occupancy._compute_candidate_positions(clusters, grid, inflated, robot_position=position)
        candidates = {str(c["label"]).upper(): c for c in candidates
                      if np.linalg.norm(np.asarray(c["position_world"]) - position[:2]) > 0.1}
        if not candidates:
            return None

        description = occupancy._format_candidates_text(list(candidates.values()))
        prompt = get_prompt(occupancy.grid_min, occupancy.grid_max, occupancy.grid_resolution,
                            float(position[0]), float(position[1]), yaw, description, depth_max=10.0)
        rgb = cv2.cvtColor(obs["camera_rgb"][0].cpu().numpy(), cv2.COLOR_RGB2BGR)
        depth = obs["camera_depth"][0].squeeze().cpu().numpy()
        depth = np.clip(np.nan_to_num(depth, nan=10.0, posinf=10.0), 0, 10)
        color_depth = cv2.applyColorMap((depth * 25.5).astype(np.uint8), cv2.COLORMAP_TURBO)
        nav_map = self._map_image(grid, inflated, clusters, candidates, position, yaw, occupancy)
        try:
            response = self.client.chat.completions.create(
                model=self.model, response_format={"type": "json_object"},
                messages=[{"role": "user", "content": [
                    {"type": "text", "text": prompt}, _image_part(np.hstack((rgb, color_depth))), _image_part(nav_map),
                ]}],
            )
            label = str(json.loads(response.choices[0].message.content or "{}")["selected_candidate"]).upper().strip()
        except (OpenAIError, ValueError, KeyError, TypeError, IndexError) as error:
            LOG.warning("LLM did not return a usable selection (%s)", type(error).__name__)
            return None

        candidate = candidates.get(label)
        # Never navigate to coordinates generated by the model; only accept a local candidate.
        return (*candidate["position_world"], candidate["yaw"]) if candidate is not None else None

    @staticmethod
    def _map_image(grid, inflated, clusters, candidates, position, yaw, occupancy):
        image = np.full((*grid.shape, 3), (240, 220, 195), dtype=np.uint8)
        image[inflated] = (0, 160, 255)
        image[grid >= 2] = (45, 40, 150)
        image = np.ascontiguousarray(image[::-1])

        def pixel(xy):
            x, y = (np.asarray(xy) - occupancy.grid_min) / occupancy.grid_resolution
            return int(x), image.shape[0] - 1 - int(y)

        def arrow(xy, heading, color):
            end = np.asarray(xy) + 0.9 * np.array([np.cos(heading), np.sin(heading)])
            cv2.arrowedLine(image, pixel(xy), pixel(end), color, 2, tipLength=0.4)

        for label, cluster in zip("ABCDEFGH", clusters, strict=False):
            point = pixel(cluster["center_world"])
            cv2.circle(image, point, 3, (0, 0, 0), -1)
            cv2.putText(image, f"Cluster {label}", point, cv2.FONT_HERSHEY_SIMPLEX, 0.35, (0, 0, 0), 1)
        for label, candidate in candidates.items():
            xy = candidate["position_world"]
            arrow(xy, candidate["yaw"], (0, 150, 0))
            cv2.putText(image, label, pixel(xy), cv2.FONT_HERSHEY_SIMPLEX, 0.45, (0, 100, 0), 1)
        arrow(position[:2], yaw, (220, 20, 20))
        return image